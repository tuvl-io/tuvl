"""``tuvl generate code`` (spec §17.6): deterministic project scaffolding — no LLM.

:func:`plan` computes every change without writing anything; ``--check``
fails when the plan is not empty (the CI drift gate) and :func:`apply` writes
it. Outputs:

- ``agents/_generated/schemas.py`` — fully generated, never hand-edited;
- ``agents/<run>.py`` per ``code`` agent — created, or merged (see
  :mod:`tuvl.codegen.stubs`);
- ``artifacts/<name>.md`` — a prompt placeholder for an ``llm``/``loop``
  agent whose prompt artifact does not exist yet (created only if missing);
- ``tests/<workflow>/<example>.yaml`` — ``Test`` documents from spec
  ``tuvl-example`` blocks (regenerated; hand-written tests are never touched,
  and generated tests whose example is gone are removed);
- a ``decide`` rules skeleton in the workflow YAML when a ``decide`` block has
  neither rules nor a model (:func:`decide_skeletons`, run before loading).
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel

from tuvl.contract.schema import WorkflowDocument
from tuvl.contract.types import parse_type
from tuvl_insight.codegen.schemas import AgentNames, CodegenError, render_schemas
from tuvl_insight.codegen.stubs import function_name, merge_stub, new_stub
from tuvl_insight.spec import Spec, SpecError, example_to_test

SCHEMAS_PATH = Path("agents/_generated/schemas.py")
TEST_HEADER = "# Generated by `tuvl generate code` from {source}. Edit the spec, not this file.\n"
_REF = re.compile(r"^artifact://([A-Za-z0-9][A-Za-z0-9_.\-]*)(?:@([1-9][0-9]*))?$")

__all__ = ["Change", "CodegenError", "Plan", "apply", "decide_skeletons", "plan", "run"]


@dataclass
class Change:
    path: Path
    action: Literal["create", "update", "delete"]
    content: str | None = None


@dataclass
class Plan:
    changes: list[Change] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def propose(
        self, project: Path, path: Path, content: str, *, only_if_missing: bool = False
    ) -> None:
        target = project / path
        if not target.exists():
            self.changes.append(Change(path, "create", content))
        elif not only_if_missing and target.read_text() != content:
            self.changes.append(Change(path, "update", content))


def apply(project: Path, changes: list[Change]) -> None:
    for change in changes:
        target = project / change.path
        if change.action == "delete":
            target.unlink(missing_ok=True)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(change.content or "")


def plan(
    project: Path,
    workflows: Mapping[str, WorkflowDocument],
    models: Mapping[str, Mapping[str, type[BaseModel]]],
    specs: list[Spec],
    *,
    artifacts: set[str] | None = None,
    only: str | None = None,
) -> Plan:
    out = Plan()
    text, names = render_schemas(workflows, models)
    out.propose(project, SCHEMAS_PATH, text)
    selected = {k: v for k, v in workflows.items() if only is None or k == only}
    _stubs(out, project, selected, names)
    _prompts(out, project, selected, artifacts or set())
    _tests(out, project, specs, only)
    return out


# ── code-agent stubs ─────────────────────────────────────────────────────────


def _contract_key(agent: Any) -> Any:
    return (
        repr(agent.inputs),
        repr(agent.outputs),
        repr(getattr(agent, "signal_outputs", None)),
        tuple(sorted(agent.routes)),
    )


def _agent_files(project: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for path in sorted((project / "agents").glob("*.py")):
        for run in re.findall(r"""@(?:\w+\.)?agent\(\s*["']([^"']+)["']""", path.read_text()):
            found.setdefault(run, path.relative_to(project))
    return found


def _stubs(
    out: Plan,
    project: Path,
    workflows: Mapping[str, WorkflowDocument],
    names: dict[tuple[str, str], AgentNames],
) -> None:
    by_run: dict[str, list[tuple[str, Any]]] = {}
    for wf in sorted(workflows):
        for agent in workflows[wf].spec.all_agents():
            if agent.engine == "code" and not agent.code.run.startswith("tuvl."):
                by_run.setdefault(agent.code.run, []).append((wf, agent))
    existing = _agent_files(project)
    for run, users in sorted(by_run.items()):
        wf, first = users[0]
        signature: AgentNames | None = names[(wf, first.id)]
        if len({_contract_key(a) for _, a in users}) > 1:
            signature = None
            where = ", ".join(f"{w}.{a.id}" for w, a in users)
            out.warnings.append(
                f"@agent('{run}') serves agents with different contracts ({where}) — typed as Any"
            )
        path = existing.get(run, Path("agents") / f"{function_name(run)}.py")
        target = project / path
        if target.exists():
            try:
                merged = merge_stub(target.read_text(), run, signature, first.description)
            except Exception as exc:
                out.warnings.append(f"{path}: not merged — {exc}")
                continue
            out.propose(project, path, merged)
        else:
            out.propose(project, path, new_stub(run, signature, first.description))


# ── prompt placeholders ──────────────────────────────────────────────────────


def _prompts(
    out: Plan, project: Path, workflows: Mapping[str, WorkflowDocument], known: set[str]
) -> None:
    on_disk = (
        {p.stem for p in (project / "artifacts").glob("*.md")}
        if (project / "artifacts").is_dir()
        else set()
    )
    for wf in sorted(workflows):
        for agent in workflows[wf].spec.all_agents():
            refs: list[str | None] = []
            if agent.engine == "llm":
                refs = [agent.llm.system, agent.llm.prompt]
            elif agent.engine == "loop":
                refs = [agent.loop.steering]
            for ref in refs:
                match = _REF.match(ref or "")
                if not match or match.group(1) in known or match.group(1) in on_disk:
                    continue
                name, version = match.group(1), int(match.group(2) or 1)
                content = (
                    f"---\nname: {name}\ntype: prompt\nversion: {version}\n"
                    f"description: Prompt for '{agent.id}' ({wf}) — placeholder from tuvl generate code.\n---\n"
                    f"TODO: write the prompt for {agent.id}: {agent.description}\n"
                )
                out.propose(
                    project, Path("artifacts") / f"{name}.md", content, only_if_missing=True
                )
                on_disk.add(name)


# ── tests from spec examples ─────────────────────────────────────────────────


def _generated_from(path: Path) -> str | None:
    try:
        data = yaml.safe_load(path.read_text())
    except (OSError, yaml.YAMLError):
        return None
    if isinstance(data, dict) and data.get("kind") == "Test":
        source = (data.get("metadata") or {}).get("generated_from")
        return str(source) if source else None
    return None


def _tests(out: Plan, project: Path, specs: list[Spec], only: str | None) -> None:
    wanted: set[Path] = set()
    for spec in specs:
        for example in spec.examples:
            try:
                test = example_to_test(spec, example)
            except SpecError as exc:
                out.warnings.append(str(exc))
                continue
            if only is not None and test.spec.workflow != only:
                continue
            path = Path("tests") / test.spec.workflow / f"{test.metadata.name}.yaml"
            if path in wanted:
                out.warnings.append(
                    f"{spec.path}: two examples render to {path} — give them distinct names"
                )
                continue
            wanted.add(path)
            target = project / path
            if target.exists() and _generated_from(target) is None:
                out.warnings.append(
                    f"{path}: hand-written test in the way of example {example.name!r} — left alone"
                )
                continue
            body = yaml.safe_dump(
                test.model_dump(mode="json", by_alias=True, exclude_defaults=True),
                sort_keys=False,
                allow_unicode=True,
            )
            out.propose(
                project, path, TEST_HEADER.format(source=test.metadata.generated_from) + body
            )
    tests_dir = project / "tests"
    if not tests_dir.is_dir():
        return
    spec_paths = {s.path for s in specs}
    for path in sorted(tests_dir.rglob("*.yaml")):
        relative = path.relative_to(project)
        source = _generated_from(path)
        if (
            relative in wanted
            or source is None
            or source.split("#")[0] not in spec_paths | _spec_files(project)
        ):
            continue
        if only is None or relative.parts[1:2] == (only,):
            out.changes.append(Change(relative, "delete"))


def _spec_files(project: Path) -> set[str]:
    directory = project / "specs"
    return (
        {str(p.relative_to(project)) for p in directory.glob("*.md")}
        if directory.is_dir()
        else set()
    )


# ── decide skeletons (raw YAML, before the project loads) ────────────────────


_DECIDE_LINE = re.compile(r"^(?P<indent>[ \t]*)decide:[ \t]*(?:\{[ \t]*\})?[ \t]*(?:#.*)?$")


def decide_skeletons(project: Path) -> Plan:
    """Fill ``decide`` blocks that have neither ``rules`` nor ``model`` with a
    rule per enum value (``when: "false"`` — never matches until written)."""
    out = Plan()
    directory = project / "workflows"
    if not directory.is_dir():
        return out
    for path in sorted(directory.rglob("*.yaml")):
        text = path.read_text()
        try:
            data = yaml.safe_load(text)
        except yaml.YAMLError:
            continue
        agents = (
            ((data or {}).get("spec") or {}).get("agents") or [] if isinstance(data, dict) else []
        )
        empty = [
            a
            for a in agents
            if isinstance(a, dict)
            and a.get("engine") == "decide"
            and not (a.get("decide") or {}).get("rules")
            and not (a.get("decide") or {}).get("model")
        ]
        if not empty:
            continue
        lines = text.splitlines()
        slots = [
            i
            for i, line in enumerate(lines)
            if _DECIDE_LINE.match(line)
            and (
                i + 1 >= len(lines)
                or _indent(lines[i + 1]) <= _indent(line)
                or not lines[i + 1].strip()
            )
        ]
        relative = path.relative_to(project)
        if len(slots) != len(empty):
            out.warnings.append(
                f"{relative}: {len(empty)} empty decide block(s) but {len(slots)} fillable "
                f"line(s) — write the rules skeleton by hand"
            )
            continue
        for i, agent in reversed(list(zip(slots, empty, strict=True))):
            values = _enum_values(agent)
            indent = _DECIDE_LINE.match(lines[i]).group("indent")  # type: ignore[union-attr]
            rules = [
                f'{indent}  - {{ when: "false", then: {v} }}  # TODO: the condition for {v}'
                for v in values
            ]
            lines[i : i + 1] = [f"{indent}decide:", f"{indent}  rules:", *rules]
        out.propose(project, relative, "\n".join(lines) + ("\n" if text.endswith("\n") else ""))
    return out


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip())


def _enum_values(agent: dict[str, Any]) -> list[str]:
    for raw in (agent.get("outputs") or {}).values():
        try:
            ref = parse_type(raw if isinstance(raw, str) else str((raw or {}).get("type", "")))
        except ValueError:
            continue
        if ref.kind == "enum" and not ref.optional:
            return list(ref.values)
    return [k for k in (agent.get("routes") or {}) if k not in ("error", "low_confidence")]


def run(project: Path, *, write: bool) -> dict[str, Any]:
    """Load *project* and compute (and with *write*, apply) every codegen change.
    The JSON ``tuvl serve mcp`` and the dev API return."""
    from tuvl.contract.registry import WORKFLOWS
    from tuvl.core.artifacts.registry import ARTIFACT_REGISTRY
    from tuvl.core.config import use_project
    from tuvl.core.config_loader import load_all_configs
    from tuvl.core.models.schemas import SCHEMA_REGISTRY
    from tuvl_insight.spec import load_specs

    use_project(project)
    skeletons = decide_skeletons(project)
    if write:
        apply(project, skeletons.changes)
    load_all_configs(project)
    result = plan(
        project,
        dict(WORKFLOWS),
        SCHEMA_REGISTRY,
        load_specs(project),
        artifacts=set(ARTIFACT_REGISTRY),
    )
    if write:
        apply(project, result.changes)
    changes = [*skeletons.changes, *result.changes]
    key = "written" if write else "would_change"
    return {
        key: [
            {"path": str(c.path), "action": c.action, **({} if write else {"content": c.content})}
            for c in changes
        ],
        "warnings": [*skeletons.warnings, *result.warnings],
    }
