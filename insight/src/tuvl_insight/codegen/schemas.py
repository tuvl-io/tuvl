"""Render ``agents/_generated/schemas.py`` (spec §17.6): Pydantic models for
every agent's inputs and outputs, each workflow's trigger input and end names,
and the model variants they reference.

The classes mirror what the runtime compiles from the contract
(:func:`tuvl.contract.types.build_model`): unknown keys are rejected, ``T?``
defaults to ``None``. Model variants ignore extra keys, so a stored row with
more columns than the contract names still validates.
"""

from __future__ import annotations

import datetime as dt
import json
import keyword
import re
import types
import typing
import uuid
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any

from pydantic import BaseModel, JsonValue

from tuvl.contract.files import FileRef
from tuvl.contract.schema import WorkflowDocument
from tuvl.contract.signals import is_reserved
from tuvl.contract.types import TypeRef, parse_field

HEADER = (
    "# Generated by `tuvl generate code` from the project's workflows. Do not edit:\n"
    "# changes are overwritten. tuvl-generated\n"
    "# ruff: noqa\n"
    "# fmt: off\n"
)
_SCALARS = {
    "str": "str",
    "int": "int",
    "float": "float",
    "bool": "bool",
    "date": "date",
    "datetime": "datetime",
    "uuid": "UUID",
    "json": "JsonValue",
    "file": "FileRef",
}


class CodegenError(ValueError):
    """The project cannot be rendered as code (a naming clash, a bad type)."""


def camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name) if part)


@dataclass
class AgentNames:
    """The generated names a code agent's signature uses."""

    inputs: str
    returns: str
    imports: list[str] = field(default_factory=list)


@dataclass
class _Render:
    models: Mapping[str, Mapping[str, type[BaseModel]]]
    lines: list[str] = field(default_factory=list)
    aliases: list[str] = field(default_factory=list)
    wanted: dict[tuple[str, str], str] = field(default_factory=dict)
    taken: set[str] = field(default_factory=set)
    used: set[str] = field(default_factory=set)  # names the module must import

    def claim(self, name: str) -> str:
        if name in self.taken:
            raise CodegenError(f"generated name {name!r} is used twice — rename an agent or model")
        self.taken.add(name)
        return name

    def model_class(self, name: str, variant: str) -> str:
        key = (name, variant)
        if key not in self.wanted:
            self.wanted[key] = name if variant == "read" else f"{name}{camel(variant)}"
        return self.wanted[key]

    def type_of(self, ref: TypeRef) -> str:
        if ref.kind == "scalar":
            text = _SCALARS[ref.name]
            self.used.add(text)
        elif ref.kind == "enum":
            self.used.add("Literal")
            text = "Literal[" + ", ".join(py(v) for v in ref.values) + "]"
        elif ref.kind == "list":
            assert ref.item is not None
            text = f"list[{self.type_of(ref.item)}]"
        else:
            text = self.model_class(ref.name, ref.variant)
        return f"{text} | None" if ref.optional else text

    def fields(self, fields: Mapping[str, Any] | None) -> list[str]:
        out: list[str] = []
        for name, raw in (fields or {}).items():
            raw = raw.model_dump(exclude_unset=True) if isinstance(raw, BaseModel) else raw
            spec = parse_field(raw)
            text = self.type_of(spec.type)
            kwargs: list[str] = []
            if spec.has_default:
                kwargs.append(f"default={py(spec.default)}")
            elif spec.type.optional:
                kwargs.append("default=None")
            attr = name
            if name.startswith("model_") or hasattr(BaseModel, name) or keyword.iskeyword(name):
                attr = f"{name}_"
                kwargs.append(f"alias={py(name)}")
            if spec.description:
                kwargs.append(f"description={py(spec.description)}")
            if kwargs == ["default=None"]:
                out.append(f"    {attr}: {text} = None")
            elif kwargs:
                self.used.add("Field")
                out.append(f"    {attr}: {text} = Field({', '.join(kwargs)})")
            else:
                out.append(f"    {attr}: {text}")
        return out

    def cls(
        self, name: str, fields: Mapping[str, Any] | None, doc: str, *, strict: bool = True
    ) -> None:
        self.claim(name)
        body = self.fields(fields)
        config = (
            'ConfigDict(extra="forbid", populate_by_name=True)'
            if strict
            else 'ConfigDict(extra="ignore")'
        )
        self.lines += [
            "",
            "",
            f"class {name}(BaseModel):",
            f"    {_docstring(doc)}",
            "",
            f"    model_config = {config}",
        ]
        if body:
            self.lines += ["", *body]


def py(value: Any) -> str:
    """A Python literal for *value*, with double-quoted strings (ruff style)."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(py(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{py(k)}: {py(v)}" for k, v in value.items()) + "}"
    return repr(value)


def _docstring(text: str) -> str:
    text = " ".join(text.split()).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'"""{text}"""'


def class_base(workflows: Mapping[str, WorkflowDocument]) -> dict[tuple[str, str], str]:
    """``(workflow, agent id)`` → class-name stem: the agent id, or the
    workflow + agent id when two workflows share an agent id."""
    count: dict[str, int] = {}
    for doc in workflows.values():
        for agent in doc.spec.all_agents():
            count[agent.id] = count.get(agent.id, 0) + 1
    return {
        (wf, agent.id): camel(agent.id) if count[agent.id] == 1 else camel(wf) + camel(agent.id)
        for wf, doc in workflows.items()
        for agent in doc.spec.all_agents()
    }


def normal_signals(agent: Any) -> list[str]:
    return [s for s in agent.routes if not is_reserved(s)]


def render_schemas(
    workflows: Mapping[str, WorkflowDocument], models: Mapping[str, Mapping[str, type[BaseModel]]]
) -> tuple[str, dict[tuple[str, str], AgentNames]]:
    """The module text and, per ``(workflow, agent)``, the names a stub uses."""
    r = _Render(models)
    names: dict[tuple[str, str], AgentNames] = {}
    stems = class_base(workflows)
    for wf in sorted(workflows):
        doc = workflows[wf]
        trigger = doc.spec.trigger
        r.cls(
            f"{camel(wf)}Input",
            trigger.input if trigger else {},
            f"Trigger input of workflow '{wf}'.",
        )
        ends = sorted({"default", *(doc.spec.outputs or {})})
        r.used.add("Literal")
        r.aliases.append(
            f"{r.claim(camel(wf) + 'End')} = Literal[{', '.join(py(e) for e in ends)}]"
        )
        for agent in doc.spec.all_agents():
            stem = stems[(wf, agent.id)]
            r.cls(f"{stem}In", agent.inputs, f"Inputs of '{agent.id}' ({wf}).")
            names[(wf, agent.id)] = _outputs(r, agent, stem, wf)
    body = list(r.lines)
    r.lines = []
    done: set[tuple[str, str]] = set()
    while len(done) < len(r.wanted):  # rendering a variant can reference another
        for key in sorted(set(r.wanted) - done):
            done.add(key)
            _model(r, *key)
    header = [HEADER.rstrip("\n"), "", "from __future__ import annotations", ""]
    if any("Literal[" in alias for alias in r.aliases):
        r.used.add("Literal")
    header += _imports(r.used)
    text = "\n".join([*header, *r.lines, *body, "", "", *r.aliases]) + "\n"
    return text, names


def _outputs(r: _Render, agent: Any, stem: str, wf: str) -> AgentNames:
    signals = normal_signals(agent)
    signal_outputs = getattr(agent, "signal_outputs", None)
    if signal_outputs is not None:
        options: list[str] = []
        for signal in signals:
            fields = signal_outputs.get(signal)
            if fields:
                cls = f"{stem}{camel(signal)}Out"
                r.cls(cls, fields, f"Outputs of '{agent.id}' when it emits '{signal}' ({wf}).")
                options.append(f"tuple[{cls}, Literal[{py(signal)}]]")
            else:
                options.append(f"Literal[{py(signal)}]")
        alias = r.claim(f"{stem}Result")
        r.aliases.append(f"{alias} = {' | '.join(options)}")
        return AgentNames(f"{stem}In", alias, [f"{stem}In", alias])
    out_cls = f"{stem}Out"
    r.cls(out_cls, agent.outputs, f"Outputs of '{agent.id}' ({wf}).")
    if set(signals) <= {"default"}:
        returns = out_cls if agent.outputs else "None"
        return AgentNames(
            f"{stem}In", returns, [f"{stem}In", *([out_cls] if agent.outputs else [])]
        )
    signal_alias = r.claim(f"{stem}Signal")
    r.aliases.append(f"{signal_alias} = Literal[{', '.join(py(s) for s in signals)}]")
    if not agent.outputs:
        return AgentNames(f"{stem}In", signal_alias, [f"{stem}In", signal_alias])
    return AgentNames(
        f"{stem}In", f"tuple[{out_cls}, {signal_alias}]", [f"{stem}In", out_cls, signal_alias]
    )


def _model(r: _Render, name: str, variant: str) -> None:
    cls = r.models.get(name, {}).get(variant)
    if cls is None:
        raise CodegenError(f"unknown model {name}.{variant} — is its ModelDefinition loaded?")
    lines = []
    for attr, info in cls.model_fields.items():
        text = _annotation(r, info.annotation)
        kwargs = [] if info.is_required() else ["default=None"]
        if kwargs and not re.search(r"(^|\| )None( \||$)", text):
            text = f"{text} | None"  # a server-filled column (id, created_at) may be absent
        if info.alias and info.alias != attr:
            kwargs.append(f"alias={py(info.alias)}")
        if kwargs == ["default=None"]:
            lines.append(f"    {attr}: {text} = None")
        elif kwargs:
            r.used.add("Field")
            lines.append(f"    {attr}: {text} = Field({', '.join(kwargs)})")
        else:
            lines.append(f"    {attr}: {text}")
    r.claim(r.wanted[(name, variant)])
    r.lines += [
        "",
        "",
        f"class {r.wanted[(name, variant)]}(BaseModel):",
        f"    {_docstring(f'Model {name} ({variant}).')}",
        "",
        '    model_config = ConfigDict(extra="ignore")',
    ]
    if lines:
        r.lines += ["", *lines]


def _annotation(r: _Render, ann: Any) -> str:
    text = _annotation_text(r, ann)
    r.used.update(re.findall(r"\b(?:date|datetime|UUID|Any|JsonValue|Literal|FileRef)\b", text))
    return text


def _annotation_text(r: _Render, ann: Any) -> str:
    if ann is None or ann is type(None):
        return "None"
    if ann is JsonValue:
        return "JsonValue"
    simple = {
        str: "str",
        int: "int",
        float: "float",
        bool: "bool",
        dt.date: "date",
        dt.datetime: "datetime",
        uuid.UUID: "UUID",
        typing.Any: "Any",
        dict: "dict[str, Any]",
    }
    if ann in simple:
        return simple[ann]
    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if origin is typing.Literal:
        return "Literal[" + ", ".join(py(a) for a in args) + "]"
    if origin in (typing.Union, types.UnionType):
        return " | ".join(_annotation_text(r, a) for a in args)
    if origin in (list, tuple, set, frozenset) and args:
        return f"list[{_annotation_text(r, args[0])}]"
    if origin is dict:
        return "dict[str, Any]"
    if ann is FileRef:
        return "FileRef"
    if isinstance(ann, type) and issubclass(ann, BaseModel):
        for model_name, variants in r.models.items():
            for variant, candidate in variants.items():
                if candidate is ann:
                    return r.model_class(model_name, variant)
    return "Any"


def _imports(used: set[str]) -> list[str]:
    out: list[str] = []
    if dates := [n for n in ("date", "datetime") if n in used]:
        out.append(f"from datetime import {', '.join(dates)}")
    if hints := [n for n in ("Any", "Literal") if n in used]:
        out.append(f"from typing import {', '.join(hints)}")
    if "UUID" in used:
        out.append("from uuid import UUID")
    pydantic = ["BaseModel", "ConfigDict", *(n for n in ("Field", "JsonValue") if n in used)]
    imports = [*out, "", f"from pydantic import {', '.join(pydantic)}"]
    if "FileRef" in used:
        imports += ["", "from tuvl.contract.files import FileRef"]
    return imports
