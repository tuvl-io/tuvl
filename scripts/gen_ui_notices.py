"""Write insight/THIRD_PARTY_LICENSES.txt from the UI's production dependencies.

The Insight bundle compiles these packages into its JavaScript, and their licenses require the
copyright notice and license text to travel with it. Run after changing ui/package.json:

    make ui-notices
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "insight" / "THIRD_PARTY_LICENSES.txt"
NAMES = ("LICENSE", "LICENCE", "COPYING", "LICENSE.md", "LICENSE.txt", "LICENSE-MIT", "license")


def main() -> int:
    raw = subprocess.run(
        ["pnpm", "licenses", "list", "--prod", "--json"],
        cwd=ROOT / "ui",
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    entries = []
    for license_id, packages in json.loads(raw).items():
        for package in packages:
            for version, path in zip(package["versions"], package["paths"], strict=False):
                entries.append((package["name"], version, license_id, Path(path)))
    entries.sort(key=lambda e: (e[0].lower(), e[1]))
    parts = [
        "Third-party software compiled into the tuvl-insight UI bundle.\n"
        "Generated by scripts/gen_ui_notices.py from ui/package.json; do not edit.\n"
    ]
    for name, version, license_id, path in entries:
        text = next(
            ((path / n).read_text(errors="replace").strip() for n in NAMES if (path / n).is_file()),
            f"(no license file in the package; declared license: {license_id})",
        )
        parts.append(f"{'=' * 78}\n{name} {version} - {license_id}\n{'=' * 78}\n{text}\n")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(entries)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
