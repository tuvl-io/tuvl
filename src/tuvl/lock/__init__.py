"""``tuvl.lock`` (spec §17.8): what a project resolves to, pinned.

- ``tuvl`` — the installed tuvl version;
- ``models`` — each AgentModel name an agent or judge uses → its model id
  (a ``provider/model`` string pins itself and is not listed);
- ``decision_models`` — provider, model id and the provider package version;
- ``artifacts`` — every ``artifact://`` reference (workflows and tests) → the
  version it resolves to and that version's sha256;
- ``judges`` — each judge reference → the model id it calls;
- ``mcp`` — per MCP server reference, each allowed tool → its input-schema hash.

:func:`build` resolves offline except for MCP, which :func:`mcp_hashes`
lists live. ``tuvl verify lock`` (and ``tuvl ship``, V024) compare a fresh
build with the file; without ``--mcp`` the MCP section is compared by tool
names only, so CI needs no MCP servers.
"""

from __future__ import annotations

import importlib.metadata
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import Any

import structlog
import yaml

from tuvl.contract.lockfile import LOCK_FILE, LockError, check_live_mcp, read, schema_hash
from tuvl.contract.schema import (
    LlmAgent,
    LoopAgent,
    McpTool,
    McpToolRef,
    TestDocument,
    ToolAgent,
    WorkflowDocument,
)

logger = structlog.get_logger(__name__)

__all__ = ["LOCK_FILE", "LockError", "check_live_mcp", "read", "schema_hash"]

FORMAT = 1
HEADER = (
    "# Generated by `tuvl generate lock`. Commit it; do not edit. `tuvl verify lock` verifies it.\n"
)


@dataclass
class Inventory:
    """Everything a project references that the lock pins."""

    models: set[str] = field(default_factory=set)
    decision_models: set[str] = field(default_factory=set)
    artifacts: set[str] = field(default_factory=set)
    judges: set[str] = field(default_factory=set)
    mcp: dict[str, set[str]] = field(default_factory=dict)


def inventory(
    workflows: Mapping[str, WorkflowDocument], tests: Iterable[TestDocument] = ()
) -> Inventory:
    from tuvl.contract.facts import document_artifact_refs

    inv = Inventory()
    for doc in workflows.values():
        for _, site, ref in document_artifact_refs(doc):
            inv.artifacts.add(ref)
            if site == "judge":
                inv.judges.add(ref)
        for agent in doc.spec.agents:
            if isinstance(agent, LlmAgent):
                inv.models.add(agent.llm.model)
            elif isinstance(agent, LoopAgent):
                inv.models.add(agent.loop.model)
                for tool in agent.loop.tools:
                    if isinstance(tool, McpToolRef):
                        inv.artifacts.add(tool.mcp)
                        inv.mcp.setdefault(tool.mcp, set()).update(tool.allow)
            elif isinstance(agent, ToolAgent) and isinstance(agent.tool, McpTool):
                inv.artifacts.add(agent.tool.server)
                inv.mcp.setdefault(agent.tool.server, set()).add(agent.tool.name)
            decide = getattr(agent, "decide", None)
            if decide is not None and decide.model is not None:
                inv.decision_models.add(decide.model.ref)
            guardrails = getattr(agent, "guardrails", None)
            for ref in (
                []
                if guardrails is None
                else [*guardrails.input, *guardrails.output, *guardrails.tools]
            ):
                inv.judges.add(ref)
    for test in tests:
        for item in test.spec.expect.judge:
            inv.artifacts.add(item.judge)
            inv.judges.add(item.judge)
    return inv


def _agent_model_id(name: str) -> str | None:
    """The model id an AgentModel name resolves to; ``None`` for a direct
    ``provider/model`` string."""
    from tuvl.core.models.agent_models import AGENT_MODEL_REGISTRY

    entry = None if "/" in name else AGENT_MODEL_REGISTRY.get(name)
    if entry is None:  # used as a literal provider/model id, like the runtime does
        return None
    return str(entry.get("model") or name)


def _provider_version(provider: str) -> str:
    found = [
        ep
        for ep in importlib.metadata.entry_points(group="tuvl.decision_providers")
        if ep.name == provider
    ]
    if not found or found[0].dist is None:
        return "unknown"
    package = found[0].dist.name
    try:
        return importlib.metadata.version(package)
    except importlib.metadata.PackageNotFoundError:
        return "unknown"


def build(inv: Inventory, mcp: Mapping[str, Mapping[str, str]] | None = None) -> dict[str, Any]:
    """The lock document for *inv* (*mcp*: live schema hashes, if listed)."""
    from tuvl.core.artifacts.registry import ARTIFACT_REGISTRY, get_version, parse_ref
    from tuvl.runtime import decision

    def is_judge(ref: str) -> bool:  # guardrails may also be regex/policy artifacts
        entry = ARTIFACT_REGISTRY.get(parse_ref(ref)[0])
        return entry is not None and entry.type == "judge"

    judge_refs = {ref for ref in inv.judges if is_judge(ref)}

    try:
        tuvl_version = importlib.metadata.version("tuvl")
    except importlib.metadata.PackageNotFoundError:
        tuvl_version = "unknown"
    doc: dict[str, Any] = {"lock": FORMAT, "tuvl": tuvl_version}

    artifacts: dict[str, Any] = {}
    judge_models: set[str] = set()
    for ref in sorted(inv.artifacts):
        name, version = parse_ref(ref)
        try:
            resolved = get_version(name, version, where="tuvl generate lock")
        except Exception as exc:
            raise LockError(f"{ref}: {exc}") from exc
        number = version or _latest(name)
        artifacts[ref] = {"version": number, "sha256": resolved.content_hash}
        if (
            ref in judge_refs
            and isinstance(resolved.content, dict)
            and resolved.content.get("model")
        ):
            judge_models.add(str(resolved.content["model"]))
    models: dict[str, str] = {}
    for name in sorted(inv.models | judge_models):
        model_id = _agent_model_id(name)
        if model_id is not None:
            models[name] = model_id
    decisions: dict[str, Any] = {}
    for name in sorted(inv.decision_models):
        try:
            config = decision.resolve_model(name)
        except decision.ProviderUnavailableError as exc:
            raise LockError(str(exc)) from exc
        provider = str(config.get("provider") or "llm")
        decisions[name] = {"provider": provider, "model": str(config.get("model") or "")}
        if provider not in ("llm", "laya", "jev"):  # a plugin's package is the model
            decisions[name]["provider_version"] = _provider_version(provider)
    judges: dict[str, Any] = {}
    for ref in sorted(judge_refs):
        content = get_version(*parse_ref(ref), where="tuvl generate lock").content
        model = (
            str(content.get("model"))
            if isinstance(content, dict) and content.get("model")
            else None
        )
        judges[ref] = {"model": models.get(model, model) if model else None}
    doc |= {
        "models": models,
        "decision_models": decisions,
        "artifacts": artifacts,
        "judges": judges,
    }
    doc["mcp"] = {
        server: {tool: (mcp or {}).get(server, {}).get(tool, "unlisted") for tool in sorted(tools)}
        for server, tools in sorted(inv.mcp.items())
    }
    return doc


def _latest(name: str) -> int:
    from tuvl.core.artifacts.registry import ARTIFACT_REGISTRY

    return int(ARTIFACT_REGISTRY[name].latest)


async def mcp_hashes(inv: Inventory) -> dict[str, dict[str, str]]:
    """List each MCP server's tools live and hash the allowed ones' schemas."""
    from tuvl.runtime.tool import mcp_session

    out: dict[str, dict[str, str]] = {}
    for server, allowed in sorted(inv.mcp.items()):
        async with mcp_session(server, "tuvl generate lock") as session:
            listed = await session.list_tools()
        found = {t.name: schema_hash(t.inputSchema) for t in listed.tools if t.name in allowed}
        missing = sorted(allowed - set(found))
        if missing:
            raise LockError(f"{server}: the server does not offer {missing}")
        out[server] = found
    return out


def render(doc: Mapping[str, Any]) -> str:
    body: str = yaml.safe_dump(dict(doc), sort_keys=False, allow_unicode=True)
    return HEADER + body


def differences(
    current: Mapping[str, Any], fresh: Mapping[str, Any], *, live_mcp: bool
) -> list[str]:
    """What changed between the lock file and a fresh build, one line each.
    Without *live_mcp* only the MCP tool names are compared."""
    out: list[str] = []
    for section in ("tuvl", "models", "decision_models", "artifacts", "judges"):
        old, new = current.get(section), fresh.get(section)
        if old == new:
            continue
        if isinstance(old, dict) and isinstance(new, dict):
            for key in sorted(set(old) | set(new)):
                if old.get(key) != new.get(key):
                    out.append(f"{section}.{key}: {old.get(key, '—')} → {new.get(key, '—')}")
        else:
            out.append(f"{section}: {old} → {new}")
    old_mcp, new_mcp = current.get("mcp") or {}, fresh.get("mcp") or {}
    for server in sorted(set(old_mcp) | set(new_mcp)):
        old_tools, new_tools = old_mcp.get(server) or {}, new_mcp.get(server) or {}
        if set(old_tools) != set(new_tools):
            out.append(f"mcp.{server}: tools {sorted(old_tools)} → {sorted(new_tools)}")
        elif live_mcp:
            for tool in sorted(new_tools):
                if old_tools[tool] != new_tools[tool]:
                    out.append(f"[V014] mcp.{server}.{tool}: input schema changed")
    return out


def merge_unlisted(fresh: dict[str, Any], current: Mapping[str, Any] | None) -> dict[str, Any]:
    """Keep previously pinned MCP hashes when this build did not list the servers."""
    old = (current or {}).get("mcp") or {}
    for server, tools in fresh.get("mcp", {}).items():
        for tool, value in tools.items():
            if value == "unlisted" and (old.get(server) or {}).get(tool):
                tools[tool] = old[server][tool]
    return fresh
